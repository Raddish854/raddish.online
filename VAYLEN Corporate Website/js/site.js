const languageCodes = Object.keys(translations);
const languageSelects = [...document.querySelectorAll(".language-control select")];
const menuToggle = document.querySelector(".menu-toggle");
const primaryNavigation = document.querySelector(".primary-nav");
const contactForm = document.querySelector("#contact-form");
const formStatus = document.querySelector("#form-status");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

function setLanguage(requestedLanguage) {
  const language = languageCodes.includes(requestedLanguage) ? requestedLanguage : "en";
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = dictionary["page.title"];
  document.querySelector('meta[name="description"]').content = dictionary["page.description"];
  document.querySelector('meta[property="og:title"]').content = dictionary["page.title"];
  document.querySelector('meta[property="og:description"]').content = dictionary["brand.slogan"];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value !== undefined) element.placeholder = value;
  });
  languageSelects.forEach((select) => { select.value = language; });
  if (menuToggle) {
    const menuIsOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-label", dictionary[menuIsOpen ? "nav.close" : "nav.open"]);
  }

  if (formStatus) formStatus.textContent = "";
  try {
    localStorage.setItem("vaylen-language", language);
  } catch (error) {
    console.warn("The selected language could not be saved in local storage.", error);
  }
}

languageSelects.forEach((select) => select.addEventListener("change", (event) => {
  setLanguage(event.currentTarget.value);
}));

function closeNavigation() {
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[document.documentElement.lang]["nav.open"]);
  primaryNavigation.classList.remove("is-open");
}

menuToggle.addEventListener("click", () => {
  const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isExpanded));
  menuToggle.setAttribute("aria-label", translations[document.documentElement.lang][isExpanded ? "nav.open" : "nav.close"]);
  primaryNavigation.classList.toggle("is-open", !isExpanded);
});
primaryNavigation.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeNavigation));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
    closeNavigation();
    menuToggle.focus();
  }
});

contactForm.addEventListener("submit", (event) => {
  event.preventDefault();
  formStatus.textContent = translations[document.documentElement.lang]["form.status"];
});

document.querySelector("#copyright-year").textContent = String(new Date().getFullYear());

if ("IntersectionObserver" in window && !reducedMotion.matches) {
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        currentObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
}

try {
  const savedLanguage = localStorage.getItem("vaylen-language");
  setLanguage(languageCodes.includes(savedLanguage) ? savedLanguage : "en");
} catch (error) {
  console.warn("The saved language could not be read from local storage.", error);
  setLanguage("en");
}
